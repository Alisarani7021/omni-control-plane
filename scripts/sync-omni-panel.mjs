/**
 * Re-pin the vendored OMNI panel headless bundle — local-only, no network.
 *
 *   node scripts/sync-omni-panel.mjs [--rebuild]
 *
 * The panel source lives in this repo under omni-panel/. With --rebuild
 * (and esbuild installed) the bundle is regenerated from omni-panel/src via
 * its build script; either way the vendored artifact is verified against
 * omni-panel/dist-headless/SHA256 and emitted as src/omni-source.ts, so the
 * control plane always bundles a hash-checked pin — never a runtime fetch.
 * The old GitHub-fetch sync died with the standalone panel repo.
 */
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const root = new URL("..", import.meta.url);
const dist = new URL("omni-panel/dist-headless/", root);

if (process.argv.includes("--rebuild")) {
  const done = spawnSync(process.execPath, ["omni-panel/scripts/build-headless.mjs"], {
    cwd: fileURLToPath(root),
    stdio: "inherit",
  });
  if (done.status !== 0) process.exit(done.status ?? 1);
}

const [src, manifest] = await Promise.all([
  readFile(new URL("omni-headless.js", dist), "utf8"),
  readFile(new URL("SHA256", dist), "utf8"),
]);
const want = manifest.trim().split(/\s+/u)[0];
const got = createHash("sha256").update(src).digest("hex");
if (want !== got) {
  console.error(`sha256 mismatch: manifest ${want} != vendored ${got}`);
  process.exit(1);
}
// Escape for embedding in a TS template literal.
const esc = src.replaceAll("\\", "\\\\").replaceAll("`", "\\`").replaceAll("${", "\\${");
const ts = `// GENERATED by scripts/sync-omni-panel.mjs — do not edit.
// OMNI panel headless tenant-node bundle, pinned & hash-verified (in-repo).
export const OMNI_SOURCE_SHA256 = "${got}";
export const OMNI_SOURCE = String.raw\`${esc}\`;
`;
await writeFile(new URL("../src/omni-source.ts", import.meta.url), ts);
console.log(`src/omni-source.ts ← omni-panel@in-repo  ${src.length} B  sha256 ${got.slice(0, 16)}…`);
